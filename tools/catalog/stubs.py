def stub_header(package: str) -> str:
    """Render the licence header of one package's stub, which is not the plain house one.

    Keeping the catalog out of the distribution keeps the vendor's *text* out of what we publish.
    It does not keep the *structure* out: a stub is field names and field types, generated from a
    vendor's definition, and it ships. So the stub carries the vendor's copyright beside ours and
    both licences, rather than claiming to be ours alone.

    The runtime module beside it does not, and the line is drawn deliberately: it carries type
    *names* and no structure at all.
    """
    source = load_sources().package(package)
    holders = "\n".join(f"# SPDX-FileCopyrightText: {holder}" for holder in source.copyright.split("; "))
