"""Stub generation: the catalog does not ship, and the structure it holds does.

A message dataclass is built at bind time by :func:`make_dataclass`, so it has no static field
set: a Component author writing ``status.drives_powered`` gets no completion, no type and no error
when they misspell it. The answer is **generated stubs, never generated runtime objects**. A stub
fails safe -- drift between the stub and the installed package is a type error while someone is
writing code -- whereas a prebuilt dataclass would be a second runtime source of truth that
silently drops a field the vendor added.

Two files per interface package, and they ship:

* ``<package>.py`` -- a real module whose PEP 562 ``__getattr__`` hands the name to
  :func:`~opensmi.ros2.runtime.messages.message_dataclass`, so the class a consumer imports is the
  same object every Binding of that type already holds;
* ``<package>.pyi`` -- the stub a type checker reads instead, generated from the catalog's
  definition text.

**The stubs are generated for exactly the packages the catalog carries**, which is the same rule
that decides the catalog's own membership rather than a second list to keep. It is also where they
are worth the most: a package with a binary release hands a consumer generated Python they can
already introspect, while the four packages nothing can install are precisely the ones a developer
has no types for.

One honest limit, stated in every generated file rather than discovered: a field whose type comes
from a package the catalog does **not** carry -- ``std_msgs/msg/Header``, say -- is annotated
``Any``. The catalog has no structure for a package it deliberately leaves to apt, and annotating
such a field as the bare base class would turn every ordinary ``header.frame_id`` into a type
error, which is worse than not knowing.
"""

