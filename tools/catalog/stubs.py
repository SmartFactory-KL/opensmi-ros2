def _class_text(description: MessageDescription, known: Mapping[str, str]) -> str:
    """Render one type as a frozen keyword-only dataclass, as the runtime builds it."""
    fields = "\n".join(f"    {field.name}: {stub_annotation(field.field_type, known)}" for field in description.fields)
    heading = (
        f"@dataclass(frozen=True, kw_only=True)\n"
        f"class {_class_name(description.type_name)}(Message):\n"
        f'    """The ROS2 message ``{description.type_name}``, as it crosses the seam."""\n'
    )
    # A type with no fields is an ordinary type with nothing in it -- a service request that takes
    # no arguments is the common one -- and `...` is how a stub spells a body that is empty.
    return f"{heading}\n{fields}\n" if fields else f"{heading}\n    ...\n"


def stub_annotation(field_type: FieldType, known: Mapping[str, str] | None = None) -> str:
    """Render the annotation one modelled field is decoded as.

    :param known: The class name to give each nested type the same stub declares. A nested type
        that is not in it is rendered ``Any``, which is the honest answer for a package the
        catalog does not carry.
    """
    if is_byte_container(field_type):
        return "bytes"
    match field_type:
        case ArrayType(element=element) | SequenceType(element=element):
            return f"tuple[{_element_annotation(element, known)}, ...]"
        case _:
            return _element_annotation(element_of(field_type), known)


def _element_annotation(element: object, known: Mapping[str, str] | None) -> str:
    """Render the annotation of what a field holds, ignoring how many of them it holds."""
    match element:
        case NestedType(type_name=type_name):
            return (known or {}).get(type_name, "Any")
        case StringType():
            return "str"
        case PrimitiveType(name=name):
            return PRIMITIVE_ANNOTATIONS[name]
        case _:  # pragma: no cover -- the three above are every element type there is
            message = f"{element!r} is not a ROS2 element type"
            raise TypeError(message)


def _class_name(type_name: str) -> str:
    """Return the name a type is imported under: the last segment of its ROS2 name."""
    return type_name.rpartition("/")[2]
